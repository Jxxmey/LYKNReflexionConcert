from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from fastapi.staticfiles import StaticFiles
from fastapi.responses import FileResponse
from motor.motor_asyncio import AsyncIOMotorClient
from dotenv import load_dotenv
import asyncio
import httpx
import random
import os

# โหลดตัวแปรจากไฟล์ .env
load_dotenv()

app = FastAPI(title="LYKN REFLEXION CONCERT API")

# CORS setup
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

current_dir = os.path.dirname(os.path.abspath(__file__))

# เปิดให้บริการโฟลเดอร์รูปไพ่ทาโรต์
tarot_card_dir = os.path.join(current_dir, "Tarot_Card")
if os.path.exists(tarot_card_dir):
    app.mount("/Tarot_Card", StaticFiles(directory=tarot_card_dir), name="Tarot_Card")

# ดึงค่า URL ของ MongoDB จาก .env (ถ้าไม่มีจะใช้ localhost เป็นค่าสำรอง)
MONGO_URI = os.getenv("MONGODB_URI", "mongodb://localhost:27017")
client = AsyncIOMotorClient(MONGO_URI)
db = client.lykn_db

async def keep_alive():
    while True:
        await asyncio.sleep(300)  # เปลี่ยนเป็น 300 วินาที (5 นาที) ตามที่ต้องการ
        async with httpx.AsyncClient() as client:
            try:
                # ให้ Ping เข้าไปที่ URL ของตัวเอง
                port = os.getenv("PORT", "8000")
                await client.get(f"http://localhost:{port}/ping")
                print("Pinged server successfully")
            except Exception as e:
                print(f"Ping failed: {e}")

@app.on_event("startup")
async def startup_event():
    asyncio.create_task(keep_alive())

@app.get("/ping")
async def ping():
    return {"status": "ok", "message": "Server is awake!"}

