frontend_dist = os.path.join(current_dir, "dist")
assets_dir = os.path.join(frontend_dist, "assets")

# เช็คให้ชัวร์ว่ามีโฟลเดอร์ assets อยู่จริงๆ ถึงจะเมาท์
if os.path.exists(assets_dir):
    app.mount("/assets", StaticFiles(directory=assets_dir), name="assets")

# Catch-all Route: ถ้าพิมพ์ path มั่วๆ หรือกด F5 ให้โหลด index.html ของ React ขึ้นมา
@app.get("/{catchall:path}")
async def serve_react_app(catchall: str):
    file_path = os.path.join(frontend_dist, catchall)
    
    # 1. ถ้าสิ่งที่ขอมาเป็นไฟล์ที่มีอยู่จริงในโฟลเดอร์ dist ให้ส่งไฟล์นั้นไป
    if os.path.isfile(file_path):
        return FileResponse(file_path)
    
    # 2. ถ้าหาไม่เจอ ให้โยน index.html ของ React กลับไปเสมอ
    index_path = os.path.join(frontend_dist, "index.html")
    if os.path.isfile(index_path):
        return FileResponse(index_path)
        
    return {"error": "Frontend build not found. Please run 'npm run build' in your React folder and move the 'dist' folder to the same directory as main.py."}